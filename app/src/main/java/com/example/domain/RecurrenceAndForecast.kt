import java.util.Locale

/**
 * Supported recurrence frequencies for Phase 6 [RecurringRuleItem].
 */
enum class RecurrenceFrequency(val wire: String) {
    WEEKLY("WEEKLY"),
    BIWEEKLY("BIWEEKLY"),
    MONTHLY("MONTHLY"),
    YEARLY("YEARLY");

    companion object {
        fun fromWire(raw: String?): RecurrenceFrequency = when (raw?.trim()?.uppercase(Locale.ROOT)) {
            "WEEKLY" -> WEEKLY
            "BIWEEKLY", "BI_WEEKLY", "FORTNIGHTLY" -> BIWEEKLY
            "YEARLY", "ANNUAL", "ANNUALLY" -> YEARLY
            else -> MONTHLY
        }
    }
}

/**
 * Cash-flow direction of a recurring rule.
 * - [EXPENSE]: posts an `expense` transaction on [RecurringRuleItem.accountId].
 * - [INCOME]: posts an `income` transaction on [RecurringRuleItem.accountId].
 * - [LOAN_REPAYMENT]: posts a repayment against [RecurringRuleItem.linkedLoanId] via
 *   `recordLoanRepaymentAtomically` (inheriting overpayment protection & Net Worth Δ = 0).
 */
enum class RecurrenceDirection(val wire: String) {
    EXPENSE("EXPENSE"),
    INCOME("INCOME"),
    LOAN_REPAYMENT("LOAN_REPAYMENT");

    companion object {
        fun fromWire(raw: String?): RecurrenceDirection = when (raw?.trim()?.uppercase(Locale.ROOT)) {
            "INCOME" -> INCOME
            "LOAN_REPAYMENT", "LOAN" -> LOAN_REPAYMENT
            else -> EXPENSE
        }
    }
}

/**
 * Execution policy for a due recurring occurrence.
 */
enum class RecurrencePostingMode(val wire: String) {
    AUTO_POST("AUTO_POST"),
    CONFIRM("CONFIRM");

    companion object {
        fun fromWire(raw: String?): RecurrencePostingMode = when (raw?.trim()?.uppercase(Locale.ROOT)) {
            "AUTO_POST", "AUTO" -> AUTO_POST
            else -> CONFIRM
        }
    }
}

/**
 * Domain model for a recurring expense, income, or loan repayment rule.
 * All monetary amounts use exact `Long` centimes via [Money].
 */
data class RecurringRuleItem(
    val id: String = "",
    val userId: String = "",
    val title: String = "",
    val direction: RecurrenceDirection = RecurrenceDirection.EXPENSE,
    val amount: Money = Money.ZERO,
    val frequency: RecurrenceFrequency = RecurrenceFrequency.MONTHLY,
    val anchorDayOfMonth: Int = 1,
    val startIsoDate: String = "",
    val nextDueIsoDate: String = "",
    val endIsoDate: String? = null,
    val postingMode: RecurrencePostingMode = RecurrencePostingMode.CONFIRM,
    val accountId: String = "acc_cash",
    val envelopeKey: String = "charges",
    val category: String = "charges",
    val linkedLoanId: String? = null,
    val sourceFinancialItemId: String? = null,
    val isPaused: Boolean = false,
    val lastPostedOccurrenceKey: String? = null,
    val skippedOccurrenceKeys: Set<String> = emptySet(),
    val createdAtEpochMs: Long = 0L,
    val updatedAtEpochMs: Long = 0L
)

/**
 * A concrete scheduled occurrence generated by [RecurrenceScheduleEngine].
 */
data class RecurringOccurrence(
    val rule: RecurringRuleItem,
    val occurrenceIsoDate: String,
    val occurrenceKey: String,
    val effectiveAmount: Money,
    val isOverdue: Boolean,
    val isDueToday: Boolean
)

/**
 * Deterministic result of attempting to post a single recurring occurrence inside a Room `@Transaction`.
 */
sealed class RecurringPostResult {
    data class Success(
        val occurrenceKey: String,
        val postedTransaction: TransactionItem?,
        val updatedRule: RecurringRuleItem,
        val loanRepaymentResult: LoanRepaymentResult.Success? = null
    ) : RecurringPostResult()

    data class AlreadyPosted(val occurrenceKey: String) : RecurringPostResult()

    data class LoanAlreadyPaidOff(val loanId: String) : RecurringPostResult()

    data class OverpaymentBlocked(
        val loanId: String,
        val remaining: Money,
        val attempted: Money
    ) : RecurringPostResult()

    data class RuleNotFound(val ruleId: String) : RecurringPostResult()

    data object InvalidRule : RecurringPostResult()
}

/**
 * Pure Kotlin deterministic recurrence scheduler with exact calendar arithmetic and
 * month-end clamping (`31 -> Feb 28/29 -> Mar 31`).
 */
object RecurrenceScheduleEngine {

    /**
     * Builds the deterministic, idempotency-enforcing occurrence key for a rule and ISO date.
     */
    fun occurrenceKey(ruleId: String, occurrenceIsoDate: String): String {
        return "${ruleId.trim()}:${occurrenceIsoDate.trim()}"
    }

    /**
     * Parses `YYYY-MM-DD` into `(year, month, day)` or returns `null` if invalid.
     */
    fun parseIsoParts(iso: String): Triple<Int, Int, Int>? {
        val clean = iso.trim()
        if (!PayCycleEngine.isValidIsoDate(clean)) return null
        val parts = clean.split("-")
        if (parts.size != 3) return null
        val y = parts[0].toIntOrNull() ?: return null
        val m = parts[1].toIntOrNull() ?: return null
        val d = parts[2].toIntOrNull() ?: return null
        return Triple(y, m, d)
    }

    fun formatIso(year: Int, month: Int, day: Int): String =
        String.format(Locale.US, "%04d-%02d-%02d", year, month, day)

    /**
     * Adds [deltaDays] days to a valid `YYYY-MM-DD` string using exact integer epoch-day math.
     */
    fun addDays(isoDate: String, deltaDays: Int): String {
        val epoch = PayCycleEngine.parseEpochDays(isoDate)
        return PayCycleEngine.epochDaysToIso(epoch + deltaDays.toLong())
    }

    /**
     * Advances [currentIso] by one recurrence period while preserving [anchorDayOfMonth]
     * with deterministic month-end clamping:
     * - Monthly anchor 31: `2026-01-31 -> 2026-02-28 -> 2026-03-31 -> 2026-04-30 -> 2026-05-31`
     * - Leap year anchor 31: `2028-01-31 -> 2028-02-29 -> 2028-03-31`
     * - Yearly anchor 29 (Feb): `2028-02-29 -> 2029-02-28 -> 2032-02-29`
     */
    fun advanceDate(
        currentIso: String,
        frequency: RecurrenceFrequency,
        anchorDayOfMonth: Int
    ): String {
        val (year, month, day) = parseIsoParts(currentIso) ?: return currentIso
        val safeAnchor = anchorDayOfMonth.coerceIn(1, 31)
        return when (frequency) {
            RecurrenceFrequency.WEEKLY -> addDays(currentIso, 7)
            RecurrenceFrequency.BIWEEKLY -> addDays(currentIso, 14)
            RecurrenceFrequency.MONTHLY -> {
                val nextMonthZeroBased = (year * 12 + (month - 1)) + 1
                val nextYear = nextMonthZeroBased / 12
                val nextMonth = (nextMonthZeroBased % 12) + 1
                val maxDay = PayCycleEngine.daysInMonth(nextYear, nextMonth)
                formatIso(nextYear, nextMonth, safeAnchor.coerceAtMost(maxDay))
            }
            RecurrenceFrequency.YEARLY -> {
                val nextYear = (year + 1).coerceAtMost(2100)
                val maxDay = PayCycleEngine.daysInMonth(nextYear, month)
                val targetDay = safeAnchor.coerceAtMost(maxDay)
                formatIso(nextYear, month, targetDay)
            }
        }
    }

    /**
     * Resolves the effective anchor day of month for a rule (falling back to startIsoDate's day).
     */
    fun resolveAnchorDay(rule: RecurringRuleItem): Int {
        if (rule.anchorDayOfMonth in 1..31) return rule.anchorDayOfMonth
        return parseIsoParts(rule.startIsoDate)?.third
            ?: parseIsoParts(rule.nextDueIsoDate)?.third
            ?: 1
    }

    /**
     * Generates all unposted, unskipped occurrences for [rule] whose date lies within
     * `[rangeStartIso, rangeEndIso]` (inclusive).
     *
     * When [includeOverdueBeforeRange] is true, overdue occurrences starting from
     * `rule.nextDueIsoDate` prior to [rangeStartIso] are also included (up to [rangeEndIso]).
     */
    fun generateOccurrencesInRange(
        rule: RecurringRuleItem,
        rangeStartIso: String,
        rangeEndIso: String,
        todayIso: String = rangeStartIso,
        postedOccurrenceKeys: Set<String> = emptySet(),
        linkedLoan: LoanItem? = null,
        includeOverdueBeforeRange: Boolean = false,
        maxOccurrences: Int = 64
    ): List<RecurringOccurrence> {
        if (rule.isPaused || !rule.amount.isPositive) return emptyList()
        if (!PayCycleEngine.isValidIsoDate(rangeStartIso) || !PayCycleEngine.isValidIsoDate(rangeEndIso)) {
            return emptyList()
        }
        if (rangeEndIso < rangeStartIso) return emptyList()

        val initialCursor = rule.nextDueIsoDate.takeIf { PayCycleEngine.isValidIsoDate(it) }
            ?: rule.startIsoDate.takeIf { PayCycleEngine.isValidIsoDate(it) }
            ?: return emptyList()

        val endCap = rule.endIsoDate?.takeIf { PayCycleEngine.isValidIsoDate(it) }
        val effectiveEnd = if (endCap != null && endCap < rangeEndIso) endCap else rangeEndIso
        if (initialCursor > effectiveEnd) return emptyList()

        // Track remaining loan balance if this rule is linked to a tracked LoanItem
        var remainingLoanCentimes: Long? = if (
            rule.direction == RecurrenceDirection.LOAN_REPAYMENT || !rule.linkedLoanId.isNullOrBlank()
        ) {
            if (linkedLoan != null) {
                if (linkedLoan.isPaidOff) return emptyList()
                linkedLoan.remaining.centimes.coerceAtLeast(0L)
            } else {
                null
            }
        } else {
            null
        }

        val anchorDay = resolveAnchorDay(rule)
        val out = mutableListOf<RecurringOccurrence>()
        var cursor = initialCursor
        var guard = 0
        val maxSteps = 512

        while (cursor <= effectiveEnd && out.size < maxOccurrences && guard < maxSteps) {
            guard++
            val key = occurrenceKey(rule.id, cursor)
            val alreadyPosted = key in postedOccurrenceKeys || key == rule.lastPostedOccurrenceKey
            val skipped = key in rule.skippedOccurrenceKeys || cursor in rule.skippedOccurrenceKeys
            val inWindow = if (includeOverdueBeforeRange) cursor <= effectiveEnd else cursor >= rangeStartIso

            if (inWindow && !alreadyPosted && !skipped) {
                val amountCentimes = if (remainingLoanCentimes != null) {
                    val rem = remainingLoanCentimes
                    if (rem <= 0L) break
                    val install = minOf(rule.amount.centimes, rem)
                    remainingLoanCentimes = rem - install
                    install
                } else {
                    rule.amount.centimes
                }
                if (amountCentimes > 0L) {
                    out.add(
                        RecurringOccurrence(
                            rule = rule,
                            occurrenceIsoDate = cursor,
                            occurrenceKey = key,
                            effectiveAmount = Money.fromCentimes(amountCentimes),
                            isOverdue = cursor < todayIso,
                            isDueToday = cursor == todayIso
                        )
                    )
                }
            }

            val next = advanceDate(cursor, rule.frequency, anchorDay)
            if (next <= cursor) break
            cursor = next
        }

        return out
    }

    /**
     * Collects all unposted, unskipped occurrences across [rules] that are due on or before [upToIso],
     * sorted chronologically.
     */
    fun findDueOccurrences(
        rules: List<RecurringRuleItem>,
        upToIso: String,
        todayIso: String = upToIso,
        postedOccurrenceKeys: Set<String> = emptySet(),
        loansById: Map<String, LoanItem> = emptyMap(),
        postingModeFilter: RecurrencePostingMode? = null
    ): List<RecurringOccurrence> {
        if (!PayCycleEngine.isValidIsoDate(upToIso)) return emptyList()
        val results = mutableListOf<RecurringOccurrence>()
        for (rule in rules) {
            if (rule.isPaused) continue
            if (postingModeFilter != null && rule.postingMode != postingModeFilter) continue
            val loan = rule.linkedLoanId?.let { loansById[it] }
            results.addAll(
                generateOccurrencesInRange(
                    rule = rule,
                    rangeStartIso = todayIso,
                    rangeEndIso = upToIso,
                    todayIso = todayIso,
                    postedOccurrenceKeys = postedOccurrenceKeys,
                    linkedLoan = loan,
                    includeOverdueBeforeRange = true,
                    maxOccurrences = 16
                )
            )
        }
        return results.sortedWith(
            compareBy<RecurringOccurrence> { it.occurrenceIsoDate }.thenBy { it.rule.title }
        )
    }
}

/**
 * Projection horizon for [CashFlowForecastEngine].
 */
enum class ForecastHorizon {
    ACTIVE_PAY_CYCLE,
    ROLLING_30_DAYS
}

/**
 * Origin of a projected scheduled cash-flow event.
 */
enum class ForecastEventSource {
    RECURRING_RULE,
    LEGACY_BILL,
    LOAN_INSTALLMENT
}

/**
 * Single projected inflow or outflow inside a [CashFlowForecastSnapshot].
 */
data class ForecastScheduledEvent(
    val id: String,
    val title: String,
    val isoDate: String,
    val amount: Money,
    val isInflow: Boolean,
    val source: ForecastEventSource,
    val ruleId: String? = null,
    val loanId: String? = null,
    val occurrenceKey: String? = null,
    val postingMode: RecurrencePostingMode? = null
)

/**
 * Single reactive Cash-Flow Forecast snapshot exposed by `MasroufiViewModel`.
 *
 * All monetary fields use exact integer `Long` centimes (`Money`). Zero `Float` or `Double`.
 *
 * Accounting invariant:
 * `projectedEndBalance = startingLiquidBalance + scheduledIncome - committedUpcomingBills`
 */
data class CashFlowForecastSnapshot(
    val horizon: ForecastHorizon = ForecastHorizon.ACTIVE_PAY_CYCLE,
    val windowStartIso: String = "",
    val windowEndIso: String = "",
    val daysRemaining: Int = 1,
    val startingLiquidBalance: Money = Money.ZERO,
    val committedUpcomingBills: Money = Money.ZERO,
    val scheduledIncome: Money = Money.ZERO,
    val projectedEndBalance: Money = Money.ZERO,
    val dailySafeToSpend: Money = Money.ZERO,
    val projectedDeficitDateIso: String? = null,
    val projectedDeficitAmount: Money = Money.ZERO,
    val upcomingItems: List<ForecastScheduledEvent> = emptyList()
) {
    val hasProjectedDeficit: Boolean
        get() = projectedDeficitDateIso != null
}

/**
 * Pure Kotlin exact `Long`-centimes Cash-Flow Forecasting engine aligned with [PayCycleEngine].
 *
 * Guarantees:
 * - Zero `Float`/`Double` arithmetic anywhere.
 * - Zero double-counting between:
 *   1. Active [RecurringRuleItem]s,
 *   2. Legacy `financial_items` bills (`itemType == "bill"`) already migrated via `sourceFinancialItemId`,
 *   3. Active `LIABILITY` [LoanItem] monthly installments already linked via `RecurringRuleItem.linkedLoanId`.
 * - Chronological day-by-day running liquid balance simulation to detect exact [CashFlowForecastSnapshot.projectedDeficitDateIso].
 */
object CashFlowForecastEngine {

    fun compute(
        netWorthSnapshot: NetWorthSnapshot,
        payCycleDay: Int,
        todayIso: String = PayCycleEngine.todayIso(),
        horizon: ForecastHorizon = ForecastHorizon.ACTIVE_PAY_CYCLE,
        recurringRules: List<RecurringRuleItem> = emptyList(),
        loans: List<LoanItem> = emptyList(),
        legacyFinancialItems: List<FinancialItem> = emptyList(),
        transactions: List<TransactionItem> = emptyList(),
        activeWindowOverride: PayCycleWindow? = null
    ): CashFlowForecastSnapshot {
        val safeToday = if (PayCycleEngine.isValidIsoDate(todayIso)) todayIso else PayCycleEngine.todayIso()
        val activeWindow = activeWindowOverride ?: PayCycleEngine.computeCycleWindow(
            payCycleDay = payCycleDay,
            monthOffset = 0,
            nowIso = safeToday
        )
        val windowStartIso = safeToday
        val windowEndIso = when (horizon) {
            ForecastHorizon.ACTIVE_PAY_CYCLE -> {
                if (activeWindow.endIso >= safeToday) activeWindow.endIso else safeToday
            }
            ForecastHorizon.ROLLING_30_DAYS -> RecurrenceScheduleEngine.addDays(safeToday, 29)
        }
        val daysRemaining = (
            PayCycleEngine.parseEpochDays(windowEndIso) - PayCycleEngine.parseEpochDays(windowStartIso) + 1L
            ).toInt().coerceAtLeast(1)

        val postedKeys = HashSet<String>()
        for (tx in transactions) {
            tx.recurringOccurrenceKey?.takeIf { it.isNotBlank() }?.let { postedKeys.add(it) }
        }
        val loansById = loans.associateBy { it.id }

        val coveredLegacyBillIds = HashSet<String>()
        val coveredLoanIds = HashSet<String>()
        val events = mutableListOf<ForecastScheduledEvent>()

        // 1. Scheduled occurrences from active RecurringRuleItems (deduplicated against posted keys)
        for (rule in recurringRules) {
            rule.sourceFinancialItemId?.takeIf { it.isNotBlank() }?.let { coveredLegacyBillIds.add(it) }
            if (!rule.isPaused) {
                rule.linkedLoanId?.takeIf { it.isNotBlank() }?.let { coveredLoanIds.add(it) }
            }
            if (rule.isPaused) continue

            val linkedLoan = rule.linkedLoanId?.let { loansById[it] }
            val occurrences = RecurrenceScheduleEngine.generateOccurrencesInRange(
                rule = rule,
                rangeStartIso = windowStartIso,
                rangeEndIso = windowEndIso,
                todayIso = safeToday,
                postedOccurrenceKeys = postedKeys,
                linkedLoan = linkedLoan,
                includeOverdueBeforeRange = true
            )
            for (occ in occurrences) {
                val isInflow = when (rule.direction) {
                    RecurrenceDirection.INCOME -> true
                    RecurrenceDirection.EXPENSE -> false
                    RecurrenceDirection.LOAN_REPAYMENT -> {
                        linkedLoan?.direction == LoanDirection.RECEIVABLE
                    }
                }
                events.add(
                    ForecastScheduledEvent(
                        id = occ.occurrenceKey,
                        title = rule.title,
                        isoDate = occ.occurrenceIsoDate,
                        amount = occ.effectiveAmount,
                        isInflow = isInflow,
                        source = ForecastEventSource.RECURRING_RULE,
                        ruleId = rule.id,
                        loanId = rule.linkedLoanId,
                        occurrenceKey = occ.occurrenceKey,
                        postingMode = rule.postingMode
                    )
                )
            }
        }

        // 2. Unmigrated legacy bills from financial_items (ONLY when not covered by a RecurringRule)
        for (item in legacyFinancialItems) {
            if (item.itemType != "bill") continue
            if (!item.amount.isPositive) continue
            if (item.id.isNotBlank() && item.id in coveredLegacyBillIds) continue

            val paidCycles = item.dateOrCycle.split(",").map { it.trim() }.filter { it.isNotBlank() }.toSet()
            if (activeWindow.cycleKey in paidCycles) continue

            val dueIso = resolveMonthlyOccurrenceInWindow(
                anchorDayOfMonth = item.dayOrTurn.coerceIn(1, 31),
                windowStartIso = windowStartIso,
                windowEndIso = windowEndIso
            ) ?: continue

            events.add(
                ForecastScheduledEvent(
                    id = "legacy_bill_${item.id}_$dueIso",
                    title = item.name.ifBlank { "Facture" },
                    isoDate = dueIso,
                    amount = item.amount,
                    isInflow = false,
                    source = ForecastEventSource.LEGACY_BILL
                )
            )
        }

        // 3. Active LIABILITY loans with monthlyPayment > 0 (ONLY when not already linked to an active RecurringRule)
        for (loan in loans) {
            if (loan.isPaidOff) continue
            if (loan.direction != LoanDirection.LIABILITY) continue
            if (!loan.monthlyPayment.isPositive) continue
            if (loan.id in coveredLoanIds) continue

            val installmentCentimes = minOf(loan.monthlyPayment.centimes, loan.remaining.centimes)
            if (installmentCentimes <= 0L) continue

            val anchorDay = loan.dueIsoDate?.let { RecurrenceScheduleEngine.parseIsoParts(it)?.third }
                ?: payCycleDay.coerceIn(1, 28)
            val dueIso = resolveMonthlyOccurrenceInWindow(
                anchorDayOfMonth = anchorDay,
                windowStartIso = windowStartIso,
                windowEndIso = windowEndIso
            ) ?: continue

            // Skip if a repayment for this loan was already recorded in this forecast window
            val alreadyRepaidInWindow = transactions.any { tx ->
                tx.loanId == loan.id && tx.isoDate >= activeWindow.startIso && tx.isoDate <= windowEndIso
            }
            if (alreadyRepaidInWindow) continue

            events.add(
                ForecastScheduledEvent(
                    id = "loan_inst_${loan.id}_$dueIso",
                    title = loan.title,
                    isoDate = dueIso,
                    amount = Money.fromCentimes(installmentCentimes),
                    isInflow = false,
                    source = ForecastEventSource.LOAN_INSTALLMENT,
                    loanId = loan.id
                )
            )
        }

        // Sort chronologically: inflows before outflows on the same day so payday covers same-day rent fairly
        val sortedEvents = events.sortedWith(
            compareBy<ForecastScheduledEvent> { it.isoDate }
                .thenByDescending { it.isInflow }
                .thenBy { it.title }
        )

        var committedOutflowCentimes = 0L
        var scheduledInflowCentimes = 0L
        for (ev in sortedEvents) {
            if (ev.isInflow) {
                scheduledInflowCentimes += ev.amount.centimes
            } else {
                committedOutflowCentimes += ev.amount.centimes
            }
        }

        val startLiquidCentimes = netWorthSnapshot.totalLiquidAssets.centimes
        val projectedEndCentimes = startLiquidCentimes + scheduledInflowCentimes - committedOutflowCentimes
        val dailySafeCentimes = if (projectedEndCentimes > 0L) {
            projectedEndCentimes / daysRemaining.toLong()
        } else {
            0L
        }

        // Day-by-day running liquid balance timeline to detect earliest deficit date and trough
        var runningCentimes = startLiquidCentimes
        var deficitDateIso: String? = if (runningCentimes < 0L) windowStartIso else null
        var lowestBalanceCentimes = runningCentimes

        val eventsByDate = sortedEvents.groupBy { it.isoDate }
        for ((dateIso, dayEvents) in eventsByDate.toSortedMap()) {
            var dayDelta = 0L
            for (ev in dayEvents) {
                dayDelta += if (ev.isInflow) ev.amount.centimes else -ev.amount.centimes
            }
            runningCentimes += dayDelta
            if (runningCentimes < lowestBalanceCentimes) {
                lowestBalanceCentimes = runningCentimes
            }
            if (runningCentimes < 0L && deficitDateIso == null) {
                deficitDateIso = if (dateIso < windowStartIso) windowStartIso else dateIso
            }
        }

        val deficitAmount = if (lowestBalanceCentimes < 0L) {
            Money.fromCentimes(-lowestBalanceCentimes)
        } else {
            Money.ZERO
        }

        return CashFlowForecastSnapshot(
            horizon = horizon,
            windowStartIso = windowStartIso,
            windowEndIso = windowEndIso,
            daysRemaining = daysRemaining,
            startingLiquidBalance = Money.fromCentimes(startLiquidCentimes),
            committedUpcomingBills = Money.fromCentimes(committedOutflowCentimes),
            scheduledIncome = Money.fromCentimes(scheduledInflowCentimes),
            projectedEndBalance = Money.fromCentimes(projectedEndCentimes),
            dailySafeToSpend = Money.fromCentimes(dailySafeCentimes),
            projectedDeficitDateIso = deficitDateIso,
            projectedDeficitAmount = deficitAmount,
            upcomingItems = sortedEvents
        )
    }

    /**
     * Finds the first calendar date in `[windowStartIso, windowEndIso]` matching [anchorDayOfMonth]
     * (with month-end clamping for shorter months).
     */
    private fun resolveMonthlyOccurrenceInWindow(
        anchorDayOfMonth: Int,
        windowStartIso: String,
        windowEndIso: String
    ): String? {
        val (startYear, startMonth, _) = RecurrenceScheduleEngine.parseIsoParts(windowStartIso) ?: return null
        val safeAnchor = anchorDayOfMonth.coerceIn(1, 31)
        for (offset in 0..2) {
            val totalMonths = startYear * 12 + (startMonth - 1) + offset
            val y = totalMonths / 12
            val m = (totalMonths % 12) + 1
            val maxDay = PayCycleEngine.daysInMonth(y, m)
            val candidate = RecurrenceScheduleEngine.formatIso(y, m, safeAnchor.coerceAtMost(maxDay))
            if (candidate in windowStartIso..windowEndIso) {
                return candidate
            }
        }
        return null
    }
}
